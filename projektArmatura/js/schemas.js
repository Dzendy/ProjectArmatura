// GENERÁTOR PORTŮ PRO ROZDĚLOVAČ
function generateManifoldPorts(pairs) {
    const width = Math.max(90, pairs * 26 + 30);
    const halfW = width / 2;
    const ports = [
        { id: 'Přívod L', dx: -halfW, dy: -12, diameter: '1"' },
        { id: 'Zpátečka L', dx: -halfW, dy: 12, diameter: '1"' },
        { id: 'Přívod R', dx: halfW, dy: -12, diameter: '1"' },
        { id: 'Zpátečka R', dx: halfW, dy: 12, diameter: '1"' }
    ];

    for (let i = 0; i < pairs; i++) {
        const x = -halfW + 28 + i * 26;
        ports.push({ id: `O${i+1}_Topný`, dx: x, dy: -25, diameter: '16×2.0' });
        ports.push({ id: `O${i+1}_Vratný`, dx: x, dy: 25, diameter: '16×2.0' });
    }
    return ports;
}

// VYPOČÍTAT KORADO RADIK OBJEM VODY
function calcKoradoRadikWaterVolume(type, heightMm, lengthMm) {
    const lengthM = lengthMm / 1000;
    const heightFactor = heightMm / 600;
    
    let baseLitersPerMeter = 6.2;
    if (type === '11') baseLitersPerMeter = 3.1;
    else if (type === '21') baseLitersPerMeter = 5.8;
    else if (type === '22') baseLitersPerMeter = 6.2;
    else if (type === '33') baseLitersPerMeter = 9.3;

    return Math.round(baseLitersPerMeter * lengthM * heightFactor * 10) / 10;
}

